#!/usr/bin/env python3
import argparse
from pathlib import Path

from pose_codegen import perturbed_pose, pose_jacobian

from wrenfold import code_generation, geometry, sym
from wrenfold.type_annotations import Matrix3, Vector3


EPSILON = 1.0e-8


def _se3_error(Rwi: Matrix3, twi: Vector3, Rwj: Matrix3, twj: Vector3,
               meas_r: Vector3, meas_t: Vector3):
    qm = geometry.Quaternion.from_rotation_vector(
        meas_r[0], meas_r[1], meas_r[2], EPSILON)
    Rm = qm.to_rotation_matrix()
    Re = Rm * Rwi.transpose() * Rwj
    te = Rm * Rwi.transpose() * (twj - twi) + meas_t

    qe = geometry.Quaternion.from_rotation_matrix(Re)
    omega = qe.to_rotation_vector(EPSILON)
    vinv = geometry.inverse_left_jacobian_of_so3(omega, EPSILON)
    upsilon = vinv * te
    return sym.vstack([omega, upsilon])


def essential_graph_residual(Rwi: Matrix3, twi: Vector3,
                             Rwj: Matrix3, twj: Vector3,
                             meas_r: Vector3, meas_t: Vector3):
    residual = _se3_error(Rwi, twi, Rwj, twj, meas_r, meas_t)
    return code_generation.OutputArg(residual, "residual")


def essential_graph_jacobian_i(Rwi: Matrix3, twi: Vector3,
                             Rwj: Matrix3, twj: Vector3,
                               meas_r: Vector3, meas_t: Vector3):
    Rwi, twi, delta = perturbed_pose(Rwi, twi)
    residual = _se3_error(Rwi, twi, Rwj, twj, meas_r, meas_t)
    Ji = pose_jacobian(residual, delta)
    return code_generation.OutputArg(Ji, "Ji")


def essential_graph_jacobian_j(Rwi: Matrix3, twi: Vector3,
                             Rwj: Matrix3, twj: Vector3,
                               meas_r: Vector3, meas_t: Vector3):
    Rwj, twj, delta = perturbed_pose(Rwj, twj)
    residual = _se3_error(Rwi, twi, Rwj, twj, meas_r, meas_t)
    Jj = pose_jacobian(residual, delta)
    return code_generation.OutputArg(Jj, "Jj")


def _generate(func):
    generator = code_generation.CppGenerator(
        code_generation.CppMatrixTypeBehavior.Eigen)
    code = code_generation.generate_function(func, generator)
    code = code.replace("void essential_graph_",
                        "XPLSLAM_GRAPHITE_HD void essential_graph_")
    return "\n".join(line.rstrip() for line in code.splitlines()) + "\n"


def main():
    repo_root = Path(__file__).resolve().parents[1]
    parser = argparse.ArgumentParser()
    parser.add_argument("--output", type=Path,
                        default=repo_root / "include" / "graphite_essential_graph_jacobians.cuh")
    output = parser.parse_args().output
    body = "\n\n".join([
        _generate(essential_graph_residual),
        _generate(essential_graph_jacobian_i),
        _generate(essential_graph_jacobian_j),
    ])
    output.write_text(
        "// Generated by tools/generate_essential_graph_jacobians.py; do not edit.\n"
        "// Twb: Rwb *= Exp(dtheta), twb += dt_world.\n"
        "#pragma once\n\n"
        "#include <Eigen/Core>\n"
        "#include <cmath>\n\n"
        "#if defined(__CUDACC__)\n"
        "#define XPLSLAM_GRAPHITE_HD __host__ __device__\n"
        "#else\n"
        "#define XPLSLAM_GRAPHITE_HD\n"
        "#endif\n\n"
        "namespace XPLSLAM::graphite_backend::generated {\n\n"
        f"{body}\n\n"
        "} // namespace XPLSLAM::graphite_backend::generated\n\n"
        "#undef XPLSLAM_GRAPHITE_HD\n",
        encoding="utf-8")


if __name__ == "__main__":
    main()
